/**
 * `/team` 命令注入的 user 消息正文 = **用户自己敲的那一行**。
 *
 * 为什么不再改写成「[系统] 用户显式要求开启…」那段说明（2026-10-01 用户反馈）：
 *   用户打的是 `/team 我需要你用智能体团队做…`，会话里却出现一条**他没打过的**系统口吻气泡，
 *   于是他看到「我发的提示词开头是一段话，而不是 /team」。注入原文之后：会话里显示的就是他
 *   自己那一行，上下文与界面逐字一致，也不会出现「用户消息里根本没有 /team 这个事实」的漂移。
 *
 * 事实来源：`parseCommand` 的 `rawInput = line.slice("/team".length + 1)`
 * （dsh-commands/lib/types/index.js:73-82，注释写明「不规范化尾部输入」）。所以这里补回前缀即可；
 * 两端空白去掉（多行粘贴时不至于带一串空行），内部换行原样保留。
 *
 * @param rawInput - `invocation.rawInput`（可能为空串/undefined）。
 * @returns 用户原样的命令行，例如 `/team` 或 `/team 只做调研`。
 */
export function teamCommandLine(rawInput) {
  const args = typeof rawInput === 'string' ? rawInput.trim() : '';
  return args === '' ? '/team' : `/team ${args}`;
}

